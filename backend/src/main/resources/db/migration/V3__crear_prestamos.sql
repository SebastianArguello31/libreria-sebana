CREATE TABLE prestamos (
                           id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           usuario_id INTEGER NOT NULL
                               REFERENCES usuarios (id) ON DELETE RESTRICT,
                           libro_id INTEGER NOT NULL
                               REFERENCES libros (id) ON DELETE RESTRICT,

                           duracion_dias SMALLINT NOT NULL,
                           fecha_prestamo DATE NOT NULL DEFAULT CURRENT_DATE,
                           fecha_vencimiento DATE NOT NULL,
                           fecha_devolucion DATE,

                           estado VARCHAR(20) NOT NULL DEFAULT 'PRESTADO',
                           creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),

                           CONSTRAINT ck_prestamos_duracion
                               CHECK (duracion_dias BETWEEN 7 AND 30),

                           CONSTRAINT ck_prestamos_estado
                               CHECK (estado IN ('PRESTADO', 'DEVUELTO', 'ANULADO')),

                           CONSTRAINT ck_prestamos_fechas
                               CHECK (
                                   fecha_vencimiento >= fecha_prestamo
                                       AND (
                                       fecha_devolucion IS NULL
                                           OR fecha_devolucion >= fecha_prestamo
                                       )
                                   ),

                           CONSTRAINT ck_prestamos_devolucion
                               CHECK (
                                   (estado = 'PRESTADO' AND fecha_devolucion IS NULL)
                                       OR (estado = 'DEVUELTO' AND fecha_devolucion IS NOT NULL)
                                       OR estado = 'ANULADO'
                                   )
);

CREATE INDEX idx_prestamos_usuario_id
    ON prestamos (usuario_id);

CREATE INDEX idx_prestamos_libro_estado_vencimiento
    ON prestamos (libro_id, estado, fecha_vencimiento);

CREATE INDEX idx_prestamos_estado
    ON prestamos (estado);